/**
 * InterviewAI – Local Answer Evaluator
 * ─────────────────────────────────────────────────────────────────
 * Grades an interview answer and explains the grade, entirely in the
 * browser. It is a transparent, rubric-driven NLP model:
 *
 *  1. Concept coverage  – which key ideas from the rubric appear in the
 *                         answer (stem-level phrase matching per sentence,
 *                         plus regex patterns). Each match keeps the
 *                         sentence that proves it ("evidence").
 *  2. Misconceptions    – regex detectors for common wrong statements.
 *  3. Semantic similarity – TF-IDF cosine similarity between the answer
 *                         and the model answer (IDF learned from the whole
 *                         knowledge base, so rare technical words count more).
 *  4. Communication     – sentence structure, examples, hedging, filler
 *                         words, repetition and length vs. difficulty.
 *
 * These signals are combined into five dimension scores and an overall
 * score with fixed, documented weights, then turned into a verdict and a
 * written explanation.
 */

const AnswerEvaluator = {

  // ─── Scoring weights (documented so the score is explainable) ───
  WEIGHTS: {
    technical:    0.35,
    completeness: 0.20,
    depth:        0.18,
    relevance:    0.15,
    clarity:      0.12,
  },

  // Expected answer length (words) per difficulty level
  TARGET_WORDS: { 1: 45, 2: 70, 3: 100, 4: 130, 5: 160 },

  VERDICTS: {
    correct:           { label: 'Correct',           icon: '✓', cls: 'correct' },
    partially_correct: { label: 'Partially Correct', icon: '◐', cls: 'partial' },
    incorrect:         { label: 'Incorrect',         icon: '✕', cls: 'incorrect' },
    off_topic:         { label: 'Off-topic',         icon: '↯', cls: 'offtopic' },
    no_answer:         { label: 'No Answer',         icon: '–', cls: 'noanswer' },
  },

  RE_EXAMPLE:   /\b(for example|for instance|e\.g\.?|such as|consider|imagine|suppose|in my (project|internship|experience|team|code)|i (used|built|implemented|worked)|we (used|built|implemented)|like when|say we have)\b|`[^`]+`|\w+\([^)]*\)|=>|\[[^\]]*\]/gi,
  RE_HEDGE:     /\b(i think|i guess|maybe|probably|not (really |very )?sure|i believe|kind of|sort of|perhaps|might be|i suppose|i feel like)\b/gi,
  RE_FILLER:    /\b(um+|uh+|you know|basically|literally|so yeah|and stuff|or something|etc etc)\b/gi,
  RE_CONNECTIVE:/\b(because|therefore|so that|which means|as a result|however|whereas|while|on the other hand|first(ly)?|second(ly)?|finally|in contrast|this is why|for example|for instance|in short|overall)\b/gi,
  RE_DONT_KNOW: /\b(i\s+(do\s+not|don'?t|dont)\s+know|no\s+idea|(i\s+am|i'?m)\s+not\s+sure|not\s+sure\s+about\s+this|i\s+have\s+not\s+(studied|learned|learnt)|skip(ping)?\s+(this|the\s+question))\b/i,

  _idf: null,

  // ─── Word statistics (IDF) learned from the rubrics seen so far ──
  // Every Gemini-written rubric is added to the corpus, so rare technical
  // words weigh more than common ones. Used only when embeddings are
  // unavailable.
  _docs: [],
  _docSet: new Set(),

  _ensureModel(item) {
    const add = (d) => { if (d && !this._docSet.has(d)) { this._docSet.add(d); this._docs.push(d); this._idf = null; } };
    if (item) {
      add(item.model);
      add((item.q || '') + ' ' + (item.concepts || []).map(c => c.label + ' ' + (c.description || '') + ' ' + (c.keys || []).join(' ')).join(' '));
    }
    if (!this._idf) this._idf = NLP.buildIdf(this._docs.length ? this._docs : ['interview answer']);
  },

  // Build a lightweight rubric when the question is not in the knowledge
  // base (e.g. a question generated by Gemini).
  buildRubric({ question, keyConcepts, modelAnswer, topic, type }) {
    let concepts = [];
    if (Array.isArray(keyConcepts) && keyConcepts.length) {
      concepts = keyConcepts.slice(0, 7).map((k, i) => ({
        label: k.label || k.name || String(k),
        w: k.weight || (i < 3 ? 3 : 2),
        core: k.core !== undefined ? !!k.core : i < 3,
        keys: (k.keywords || k.keys || [k.label || String(k)]).map(String),
        why: k.why || k.explanation || 'This idea is expected in a complete answer.',
      }));
    } else if (type === 'behavioral') {
      concepts = Object.values(Taxonomy.STAR);
    } else {
      // Fall back to the most informative words in the question itself.
      this._ensureModel();
      const stems = [...new Set(NLP.contentStems(question))];
      const words = NLP.tokenize(question).filter(t => !NLP.isStopword(t) && t.length > 3);
      const byStem = Object.create(null);
      for (const w of words) byStem[NLP.stem(w)] = byStem[NLP.stem(w)] || w;
      const ranked = stems
        .filter(s => byStem[s])
        .sort((a, b) => ((b in this._idf) ? this._idf[b] : this._idf.__default) - ((a in this._idf) ? this._idf[a] : this._idf.__default))
        .slice(0, 5);
      concepts = ranked.map((s, i) => ({
        label: `Addresses "${byStem[s]}"`,
        w: i < 2 ? 3 : 2,
        core: i < 2,
        keys: [byStem[s]],
        why: `The question is about "${byStem[s]}", so a relevant answer must discuss it directly.`,
      }));
    }
    return {
      id: 'generated',
      topic: topic || 'General',
      type: type || 'technical',
      q: question,
      model: modelAnswer || '',
      concepts,
      mis: [],
      _source: keyConcepts && keyConcepts.length ? 'ai-rubric' : 'generic',
    };
  },

  // ═══════════════════════════════════════════════════════════════
  //   MAIN ENTRY
  // ═══════════════════════════════════════════════════════════════
  // semantic (optional): measurements from the embedding model –
  //   { similarity 0–1, conceptScores: [{score 0–1, evidence}|null], flags: [...] }
  evaluate({ question, answer, difficulty, rubric, semantic = null }) {
    const level = Math.min(5, Math.max(1, Number(difficulty) || 2));
    const item = rubric || this.buildRubric({ question });
    this._ensureModel(item);
    const source = item._source || 'kb';
    const isBehavioral = item.type === 'behavioral';
    const text = String(answer || '').trim();

    // ── Basic statistics ────────────────────────────────────────────
    const sentences = NLP.splitSentences(text);
    const words = NLP.wordCount(text);
    const stems = NLP.contentStems(text);
    const stemSet = new Set(stems);
    const sentenceInfo = sentences.map(s => ({ text: s, stems: new Set(NLP.contentStems(s)) }));
    const examples = (text.match(this.RE_EXAMPLE) || []).length;
    const hedges = (text.match(this.RE_HEDGE) || []).map(h => h.toLowerCase());
    const fillers = (text.match(this.RE_FILLER) || []).map(f => f.toLowerCase());
    const connectives = (text.match(this.RE_CONNECTIVE) || []).length;
    const numbers = (text.match(/\b\d+(\.\d+)?\s?(%|x|ms|s|seconds|minutes|hours|days|weeks|users|k|mb|gb)?\b/gi) || []).length;
    const avgSentence = sentences.length ? words / sentences.length : words;
    const ttr = NLP.typeTokenRatio(text);

    const stats = {
      words, sentences: sentences.length, avg_sentence_length: Math.round(avgSentence),
      examples, hedges: hedges.length, fillers: fillers.length, numbers,
      target_words: this.TARGET_WORDS[level],
    };

    // ── "I don't know" / empty answers ──────────────────────────────
    if (stems.length < 3 || (this.RE_DONT_KNOW.test(text) && stems.length < 15)) {
      return this._noAnswerResult(item, stats, level, text);
    }

    // ── 1. Misconceptions (wrong statements) ────────────────────────
    const misconceptions = [];
    for (const m of item.mis || []) {
      const match = text.match(m.re);
      if (!match) continue;
      const quote = this._sentenceContaining(sentences, match[0]) || match[0];
      const fix = m.fix.replace(/\*\*/g, '');
      const existing = misconceptions.find(x => x.quote === quote);
      if (existing) existing.correction += ' ' + fix;
      else misconceptions.push({ quote, correction: fix });
    }
    // Note: sentences the embedding model flags as close to a known false
    // claim are NOT penalised here – embeddings cannot reliably tell "X proves Y"
    // from "X does not prove Y". They are sent to the LLM judge to confirm.
    const wrongSentences = new Set(misconceptions.map(m => this._trimQuote(m.quote)));

    // ── 2. Concept coverage ─────────────────────────────────────────
    const concepts = item.concepts.map((c, i) => {
      const res = this._matchConcept(c, sentenceInfo, stemSet, text);
      // Meaning-based match from the embedding model can upgrade a keyword miss
      const sc = semantic?.conceptScores?.[i];
      if (sc) {
        res.semantic = sc.score;
        if (sc.score >= 0.8 && res.status !== 'covered') { res.status = 'covered'; res.evidence = this._trimQuote(sc.evidence); }
        else if (sc.score >= 0.55 && res.status === 'missed') { res.status = 'partial'; res.evidence = this._trimQuote(sc.evidence); }
      }
      // A concept "mentioned" only inside a wrong statement earns no credit
      if (res.status !== 'missed' && wrongSentences.has(res.evidence)) res.status = 'contradicted';
      return res;
    });
    const totalW = concepts.reduce((s, c) => s + c.w, 0) || 1;
    const credit = (c) => c.status === 'covered' ? 1 : c.status === 'partial' ? 0.5 : 0;
    const coverage = concepts.reduce((s, c) => s + c.w * credit(c), 0) / totalW;
    const core = concepts.filter(c => c.core);
    const coreW = core.reduce((s, c) => s + c.w, 0);
    const coreCoverage = coreW ? core.reduce((s, c) => s + c.w * credit(c), 0) / coreW : coverage;
    const extra = concepts.filter(c => !c.core);
    const extraW = extra.reduce((s, c) => s + c.w, 0);
    const extraCoverage = extraW ? extra.reduce((s, c) => s + c.w * credit(c), 0) / extraW : coverage;

    // ── 3. Semantic similarity (TF-IDF cosine) ──────────────────────
    const answerVec = NLP.tfidfVector(stems, this._idf);
    const modelVec = NLP.tfidfVector(NLP.contentStems(item.model || ''), this._idf);
    const rubricText = item.q + ' ' + item.concepts.map(c => (c.keys || []).join(' ')).join(' ');
    const rubricVec = NLP.tfidfVector(NLP.contentStems(rubricText), this._idf);
    const questionVec = NLP.tfidfVector(NLP.contentStems(item.q || question), this._idf);
    const simModel = item.model ? NLP.cosine(answerVec, modelVec) : coverage * 0.4;
    const simRubric = NLP.cosine(answerVec, rubricVec);
    const simQuestion = NLP.cosine(answerVec, questionVec);
    const simModelN = semantic ? semantic.similarity : this._clamp(simModel / 0.40);
    const relevanceN = this._clamp(Math.max(simRubric / 0.30, simModelN, coverage * 1.2));
    const restatesQuestion = simQuestion > 0.7 && coverage < 0.25 && words < 40;

    // ── 4. Dimension scores (0–100) ─────────────────────────────────
    const lengthFactor = this._clamp(words / this.TARGET_WORDS[level]);
    const misPenalty = Math.min(60, misconceptions.length * 22);

    let technical, depth;
    if (isBehavioral) {
      // For behavioural questions "technical" = structure of the story (STAR)
      technical = 100 * (0.8 * coverage + 0.2 * simModelN);
      const firstPerson = (text.match(/\bi\s+(\w+ed|built|led|took|wrote|made|ran|spoke|set|did)\b/gi) || []).length;
      const specificity = this._clamp(numbers / 2) * 0.35 + this._clamp(firstPerson / 4) * 0.4 + this._clamp(examples / 2) * 0.25;
      depth = 100 * (0.45 * specificity + 0.35 * lengthFactor + 0.2 * extraCoverage);
    } else {
      technical = 100 * (0.72 * coverage + 0.28 * simModelN);
      if (coverage === 0 && simModelN < 0.3) technical *= 0.5;
      const termDensity = this._clamp((stemSet.size / Math.max(1, words)) * 1.6);
      depth = 100 * (0.45 * extraCoverage + 0.25 * lengthFactor + 0.15 * this._clamp(examples / 2) + 0.15 * termDensity);
      depth *= (0.35 + 0.65 * coverage);           // depth only counts when the basics are right
    }
    technical = Math.max(0, technical - misPenalty);

    const completeness = 100 * (0.65 * coreCoverage + 0.35 * coverage) * (0.75 + 0.25 * lengthFactor);
    const relevance = 100 * relevanceN * (restatesQuestion ? 0.6 : 1);

    // Clarity: start from 100 and apply explainable deductions/bonuses
    const clarityNotes = [];
    let clarity = 88;
    if (words < 15) { clarity -= 35; clarityNotes.push('very short answer'); }
    else if (words < 30) { clarity -= 15; clarityNotes.push('brief answer'); }
    if (avgSentence > 35) { clarity -= 18; clarityNotes.push(`long sentences (avg ${Math.round(avgSentence)} words)`); }
    else if (avgSentence > 26) { clarity -= 8; clarityNotes.push(`fairly long sentences (avg ${Math.round(avgSentence)} words)`); }
    if (hedges.length) { clarity -= Math.min(24, hedges.length * 8); clarityNotes.push(`${hedges.length} hedging phrase${hedges.length > 1 ? 's' : ''}`); }
    if (fillers.length) { clarity -= Math.min(16, fillers.length * 4); clarityNotes.push(`${fillers.length} filler word${fillers.length > 1 ? 's' : ''}`); }
    if (words > 60 && ttr < 0.4) { clarity -= 12; clarityNotes.push('repetitive wording'); }
    if (connectives >= 2) { clarity += 8; clarityNotes.push('good use of linking words'); }
    if (examples > 0) { clarity += 4; }
    clarity = Math.max(5, Math.min(100, clarity));

    // ── 5. Overall score ────────────────────────────────────────────
    const W = this.WEIGHTS;
    let overall = W.technical * technical + W.completeness * completeness + W.depth * depth
                + W.relevance * relevance + W.clarity * clarity;

    // ── 6. Verdict ──────────────────────────────────────────────────
    let verdict;
    // With embeddings, "off-topic" means low meaning-similarity to the model answer
    const offTopic = semantic ? (semantic.similarity < 0.35 && coverage < 0.15) : (relevance < 22 && coverage < 0.12);
    if (offTopic) {
      verdict = 'off_topic';
      overall = Math.min(overall, 18);
    } else if (misconceptions.length > 0 && coreCoverage < 0.5) {
      verdict = 'incorrect';
      overall = Math.min(overall, 38);
    } else if (overall >= 70 && coreCoverage >= 0.7 && misconceptions.length === 0) {
      verdict = 'correct';
    } else if (overall >= 38 || coreCoverage >= 0.34) {
      verdict = 'partially_correct';
      if (misconceptions.length) overall = Math.min(overall, 65);
      overall = Math.max(overall, 38);
    } else {
      verdict = 'incorrect';
    }

    const scores = {
      technical_correctness: Math.round(technical),
      relevance: Math.round(relevance),
      depth_of_knowledge: Math.round(depth),
      clarity: Math.round(clarity),
      completeness: Math.round(completeness),
      overall_score: Math.round(Math.max(0, Math.min(100, overall))),
    };

    // ── 7. Confidence in this evaluation ────────────────────────────
    const baseConf = source === 'kb' ? 0.88 : source === 'ai-rubric' ? 0.72 : 0.5;
    const s = scores.overall_score;
    const margin = Math.min(Math.abs(s - 38), Math.abs(s - 70));
    let confidence = baseConf * (0.78 + 0.22 * this._clamp(margin / 15));
    if (words < 20) confidence = Math.min(0.95, confidence + 0.05);  // short answers are easy to judge
    const confidenceLabel = confidence >= 0.75 ? 'High' : confidence >= 0.58 ? 'Medium' : 'Low';

    const result = {
      ...scores,
      verdict,
      verdict_label: this.VERDICTS[verdict].label,
      confidence: Math.round(confidence * 100) / 100,
      confidence_label: confidenceLabel,
      evaluation_type: isBehavioral ? 'behavioral' : 'technical',
      rubric_source: source,
      engine: 'InterviewAI NLP Evaluator v2',
      topic: item.topic,
      concepts: concepts.map(c => ({
        label: c.label, status: c.status, weight: c.w, core: !!c.core,
        evidence: c.evidence || '', why: c.why || '',
      })),
      misconceptions,
      model_answer: item.model || '',
      similarity: Math.round((semantic ? semantic.similarity : simModel) * 100),
      coverage: Math.round(coverage * 100),
      core_coverage: Math.round(coreCoverage * 100),
      answer_stats: stats,
      restates_question: restatesQuestion,
    };

    result.dimension_reasons = this._dimensionReasons(result, { clarityNotes, lengthFactor, isBehavioral, level });
    result.dimension_labels = isBehavioral
      ? { technical_correctness: 'STAR structure', relevance: 'Relevance', depth_of_knowledge: 'Specificity', clarity: 'Clarity', completeness: 'Completeness' }
      : { technical_correctness: 'Technical accuracy', relevance: 'Relevance', depth_of_knowledge: 'Depth', clarity: 'Clarity', completeness: 'Completeness' };

    const explanation = this._explain(result, { level, isBehavioral });
    result.summary = explanation.summary;
    result.explanation = explanation.paragraphs;
    result.improvement_tips = explanation.tips;
    result.strengths = explanation.strengths;
    result.weaknesses = explanation.weaknesses;
    result.feedback = explanation.summary;
    result.next_difficulty_action = s >= 80 && verdict === 'correct' ? 'increase' : s >= 55 ? 'maintain' : 'decrease';
    return result;
  },

  // ─── Concept matching ─────────────────────────────────────────────
  _matchConcept(concept, sentenceInfo, answerStemSet, rawText) {
    const out = { ...concept, status: 'missed', evidence: '' };
    let bestPartial = 0;
    let partialEvidence = '';

    for (const key of concept.keys || []) {
      const keyStems = [...new Set(NLP.contentStems(key))];
      if (keyStems.length === 0) continue;

      // Full match: every word of the phrase in the same sentence
      for (const s of sentenceInfo) {
        if (keyStems.every(k => s.stems.has(k))) {
          out.status = 'covered';
          out.evidence = this._trimQuote(s.text);
          return out;
        }
      }
      // Partial: most words of a multi-word phrase appear somewhere
      if (keyStems.length >= 2) {
        const found = keyStems.filter(k => answerStemSet.has(k)).length / keyStems.length;
        if (found > bestPartial) {
          bestPartial = found;
          const hit = sentenceInfo.find(s => keyStems.some(k => s.stems.has(k)));
          partialEvidence = hit ? this._trimQuote(hit.text) : '';
        }
      }
    }

    if (concept.re) {
      const m = rawText.match(concept.re);
      if (m) {
        out.status = 'covered';
        const sentence = sentenceInfo.find(s => s.text.toLowerCase().includes(m[0].toLowerCase()));
        out.evidence = this._trimQuote(sentence ? sentence.text : m[0]);
        return out;
      }
    }

    if (bestPartial >= 0.5) {
      out.status = 'partial';
      out.evidence = partialEvidence;
    }
    return out;
  },

  // ─── Result for empty / "I don't know" answers ────────────────────
  _noAnswerResult(item, stats, level, text) {
    const isBehavioral = item.type === 'behavioral';
    const coreLabels = item.concepts.filter(c => c.core).map(c => c.label);
    const summary = text
      ? 'You did not attempt an answer, so no knowledge could be credited for this question.'
      : 'No answer was submitted.';
    return {
      technical_correctness: 0, relevance: 0, depth_of_knowledge: 0, clarity: 0, completeness: 0,
      overall_score: text ? 5 : 0,
      verdict: 'no_answer',
      verdict_label: this.VERDICTS.no_answer.label,
      confidence: 0.97, confidence_label: 'High',
      evaluation_type: isBehavioral ? 'behavioral' : 'technical',
      rubric_source: item._source || 'kb',
      engine: 'InterviewAI NLP Evaluator v2',
      topic: item.topic,
      concepts: item.concepts.map(c => ({ label: c.label, status: 'missed', weight: c.w, core: !!c.core, evidence: '', why: c.why || '' })),
      misconceptions: [],
      model_answer: item.model || '',
      similarity: 0, coverage: 0, core_coverage: 0,
      answer_stats: stats,
      dimension_reasons: {},
      dimension_labels: isBehavioral
        ? { technical_correctness: 'STAR structure', relevance: 'Relevance', depth_of_knowledge: 'Specificity', clarity: 'Clarity', completeness: 'Completeness' }
        : { technical_correctness: 'Technical accuracy', relevance: 'Relevance', depth_of_knowledge: 'Depth', clarity: 'Clarity', completeness: 'Completeness' },
      summary,
      explanation: [
        summary,
        `A good answer to this question would cover: ${coreLabels.join('; ')}. Read the model answer below and try to explain it in your own words.`,
        'In a real interview, saying "I don\'t know" outright is worse than reasoning out loud. Share what you do know, connect it to something related, and be honest about the gap – interviewers reward the thought process.',
      ],
      improvement_tips: [
        'Study the model answer and the key concepts listed below.',
        'In interviews, attempt a partial answer and explain your reasoning instead of skipping.',
        `Review ${item.topic} fundamentals: ${(Taxonomy.TOPICS[item.topic] || {}).resources || 'official documentation and practice questions'}.`,
      ],
      strengths: [],
      weaknesses: [`No answer given for a ${item.topic} question`],
      feedback: summary,
      next_difficulty_action: 'decrease',
    };
  },

  // ─── Why each dimension got its score ─────────────────────────────
  _dimensionReasons(r, { clarityNotes, lengthFactor, isBehavioral, level }) {
    const covered = r.concepts.filter(c => c.status === 'covered').length;
    const partial = r.concepts.filter(c => c.status === 'partial').length;
    const total = r.concepts.length;
    const coreMissed = r.concepts.filter(c => c.core && (c.status === 'missed' || c.status === 'contradicted')).length;
    const st = r.answer_stats;

    const reasons = {};
    if (isBehavioral) {
      reasons.technical_correctness = `${covered} of ${total} story elements present${partial ? ` (+${partial} partially)` : ''}; interviewers expect Situation, Task, Action and Result.`;
      reasons.depth_of_knowledge = `${st.numbers} measurable detail${st.numbers === 1 ? '' : 's'} and ${st.examples} concrete reference${st.examples === 1 ? '' : 's'}; specific, first-person detail makes a story credible.`;
    } else {
      const contra = r.concepts.filter(c => c.status === 'contradicted').length;
      reasons.technical_correctness = `${covered} of ${total} key concepts explained correctly${partial ? `, ${partial} partially` : ''}${contra ? `, ${contra} stated incorrectly` : ''}; ${r.similarity}% similarity to the model answer` +
        (r.misconceptions.length ? `; −${Math.min(60, r.misconceptions.length * 22)} points for ${r.misconceptions.length} factual error${r.misconceptions.length > 1 ? 's' : ''}.` : '.');
      reasons.depth_of_knowledge = `${r.concepts.filter(c => !c.core && c.status !== 'missed').length} of ${r.concepts.filter(c => !c.core).length} advanced points covered, ${st.examples ? st.examples + ' example(s)' : 'no examples'}, ${st.words} words vs ~${st.target_words} expected at level ${level}.`;
    }
    reasons.completeness = coreMissed
      ? `${coreMissed} essential point${coreMissed > 1 ? 's' : ''} missing (${r.core_coverage}% of must-have content covered).`
      : `All essential points addressed (${r.core_coverage}% of must-have content).`;
    reasons.relevance = r.restates_question
      ? 'The answer mostly repeats the question instead of answering it.'
      : r.relevance >= 70 ? 'Stays focused on what was asked.'
      : r.relevance >= 40 ? 'Partly on-topic; some of the answer does not address the question directly.'
      : 'Most of the answer does not address the question that was asked.';
    reasons.clarity = clarityNotes.length ? `Assessed on structure: ${clarityNotes.join(', ')}.` : 'Clear, well-paced sentences with no hedging or filler.';
    return reasons;
  },

  // ─── Natural-language explanation ─────────────────────────────────
  _explain(r, { level, isBehavioral }) {
    const covered = r.concepts.filter(c => c.status === 'covered');
    const partial = r.concepts.filter(c => c.status === 'partial');
    const contradicted = r.concepts.filter(c => c.status === 'contradicted');
    const missedCore = r.concepts.filter(c => c.status === 'missed' && c.core);
    const missedExtra = r.concepts.filter(c => c.status === 'missed' && !c.core);
    const st = r.answer_stats;
    const errWord = isBehavioral ? 'red flag' : 'factual error';

    // "A; B and C" – concept labels are written in sentence case
    const name = (c) => c.label;
    const list = (arr) => {
      const names = arr.map(name);
      if (names.length <= 1) return names.join('');
      return names.slice(0, -1).join('; ') + ' and ' + names[names.length - 1];
    };

    // ── Headline summary ──
    let summary;
    switch (r.verdict) {
      case 'correct':
        summary = missedExtra.length
          ? `Correct. You covered every essential point an interviewer expects here. To make it outstanding, also mention: ${list(missedExtra.slice(0, 2))}.`
          : 'Correct and thorough. You covered every key idea an interviewer looks for in this question.';
        break;
      case 'partially_correct':
        if (covered.length) {
          summary = `Partially correct. You got ${covered.length} of ${r.concepts.length} key points right, but ` +
            (missedCore.length ? `missed something essential: ${list(missedCore.slice(0, 2))}.` : 'the explanation needs more depth and precision.') +
            (r.misconceptions.length ? ` It also contains a ${errWord}.` : '');
        } else {
          summary = `Partially correct. You are on the right topic but only touch the key ideas loosely` +
            (missedCore.length ? ` – still missing: ${list(missedCore.slice(0, 2))}.` : '.');
        }
        break;
      case 'incorrect':
        if (r.misconceptions.length) {
          summary = isBehavioral
            ? 'Weak answer. It raises a red flag interviewers watch for, and it does not tell a concrete story.'
            : `Incorrect. Your answer states something that is technically wrong about the core concept${contradicted.length ? ` (${list(contradicted.slice(0, 2))})` : ''}.`;
        } else {
          summary = isBehavioral
            ? `Weak answer. It does not give the interviewer a concrete example – missing: ${list(missedCore.slice(0, 3))}.`
            : `Incorrect. The answer does not explain the core ideas this question is testing${missedCore.length ? ` – missing: ${list(missedCore.slice(0, 3))}` : ''}.`;
        }
        break;
      case 'off_topic':
        summary = `Off-topic. Your answer does not address what was asked${r.topic ? ` (a ${r.topic} question)` : ''}, so no credit could be given.`;
        break;
      default:
        summary = 'No answer was given.';
    }

    // ── Detailed paragraphs ──
    const paragraphs = [];

    if (covered.length) {
      paragraphs.push(`**What you got right.** You correctly addressed ${covered.length > 1 ? 'these points' : 'this point'}: ${list(covered)}.` +
        (partial.length ? ` You also hinted at ${list(partial)}, but not clearly enough for full credit – name the idea explicitly and explain it in a full sentence.` : ''));
    } else if (partial.length) {
      paragraphs.push(`**What you got right.** You hinted at ${list(partial)}, but did not state ${partial.length > 1 ? 'these ideas' : 'this idea'} clearly enough to earn full credit.`);
    }

    if (r.misconceptions.length) {
      const title = isBehavioral ? '**Red flag.** ' : '**What was wrong.** ';
      paragraphs.push(title + r.misconceptions.map(m => `You wrote "${this._trimQuote(m.quote, 110).replace(/[.!]+$/, '')}". ${m.correction}`).join(' '));
    }

    if (missedCore.length && r.verdict !== 'off_topic') {
      paragraphs.push(`**What was missing.** ` + missedCore.slice(0, 3).map(c => `${c.label} – ${c.why}`).join(' '));
    } else if (missedExtra.length && r.verdict !== 'off_topic') {
      paragraphs.push(`**How to go further.** ${missedExtra.slice(0, 2).map(c => `${c.label} – ${c.why}`).join(' ')}`);
    }

    if (r.verdict === 'off_topic') {
      const coreNames = list(r.concepts.filter(c => c.core).slice(0, 3));
      paragraphs.push(`The question is looking for: ${coreNames || 'a specific concept'}. Re-read the question and answer it directly in your first sentence before adding background.`);
    }
    if (r.restates_question) {
      paragraphs.push('Most of your answer repeats the question back. Interviewers notice this immediately – open with a direct one-sentence answer instead.');
    }

    // Communication observations
    const comms = [];
    const levelName = ['', 'beginner', 'intermediate', 'moderate', 'advanced', 'expert'][level];
    if (st.words < st.target_words * 0.5 && r.verdict !== 'off_topic') {
      comms.push(`your answer is ${st.words} words; ${/^[aeiou]/.test(levelName) ? 'an' : 'a'} ${levelName}-level question usually needs around ${st.target_words}`);
    }
    if (!isBehavioral && st.examples === 0 && level >= 2 && r.verdict !== 'off_topic') comms.push('there is no concrete example, code snippet or real use-case to back up the explanation');
    if (st.hedges > 0) comms.push('hedging phrases (e.g. "I think", "maybe") make you sound unsure – state facts confidently');
    if (isBehavioral && st.numbers === 0 && r.verdict !== 'off_topic') comms.push('the story has no measurable result (a number, percentage or concrete outcome)');
    if (comms.length) paragraphs.push(`**Delivery.** ${comms.map((c, i) => i === 0 ? c.charAt(0).toUpperCase() + c.slice(1) : c).join('; ')}.`);

    // ── Tips (max 4, most important first) ──
    const tips = [];
    for (const m of r.misconceptions.slice(0, 2)) tips.push(`**${isBehavioral ? 'Avoid this' : 'Correct this'}:** ${m.correction}`);
    for (const c of missedCore.slice(0, 2)) tips.push(`**Add: ${name(c)}.** ${c.why}`);
    if (isBehavioral && r.concepts.some(c => /^Result/.test(c.label) && c.status !== 'covered')) tips.push('End the story with a measurable result: "…which cut review time by 40%" or "…and we delivered two days early".');
    if (!isBehavioral && st.examples === 0 && level >= 2) tips.push('Back up your explanation with a concrete example from a project, or a short code snippet.');
    if (st.words < st.target_words * 0.5) tips.push(`Aim for about ${st.target_words} words, structured as: direct answer → how it works → example → trade-offs.`);
    if (st.hedges > 1) tips.push('Replace "I think / maybe" with direct statements; if unsure, say what you know and reason through the rest.');
    for (const c of missedExtra.slice(0, 2)) if (tips.length < 4) tips.push(`**To stand out:** also cover ${name(c)}.`);
    if (tips.length === 0) tips.push('Strong answer. To polish it further, mention a trade-off or a real project where you applied this.');

    // ── Strengths / weaknesses (short bullet form) ──
    const strengths = covered.slice(0, 3).map(c => `Covered: ${name(c)}`);
    if (st.examples > 0 && r.verdict !== 'off_topic' && r.verdict !== 'incorrect') strengths.push('Supported the answer with a concrete example');
    if (st.hedges === 0 && st.words >= 30 && r.clarity >= 75 && r.verdict !== 'off_topic') strengths.push('Clear, confident delivery');
    const weaknesses = [
      ...r.misconceptions.map(m => `${isBehavioral ? 'Red flag' : 'Factual error'}: ${m.correction.split(/(?<=\.)\s/)[0]}`),
      ...missedCore.map(c => `Missed: ${c.label}`),
    ];
    if (!weaknesses.length && missedExtra.length) weaknesses.push(`Could add: ${missedExtra[0].label}`);

    return { summary, paragraphs, tips: tips.slice(0, 4), strengths: strengths.slice(0, 4), weaknesses: weaknesses.slice(0, 4) };
  },

  // ─── Helpers ──────────────────────────────────────────────────────
  _clamp(x) { return Math.max(0, Math.min(1, x)); },

  _trimQuote(s, max = 160) {
    const t = String(s || '').replace(/\s+/g, ' ').trim();
    return t.length > max ? t.slice(0, max - 1).trim() + '…' : t;
  },

  _sentenceContaining(sentences, fragment) {
    const f = fragment.toLowerCase();
    return sentences.find(s => s.toLowerCase().includes(f));
  },
};

